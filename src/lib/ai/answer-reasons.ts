/** Одна находка контроля — то, что оператор должен увидеть глазами. */
export interface ReasonDetail {
  reason: HumanReviewReason;
  /** Короткое человеческое описание конкретной находки, а не класса. */
  detail: string;
}

/**
 * Что движок положил в промпт из тарифной сетки.
 *
 * Разделы и число строк, а не сами строки: тридцать строк матрицы в отладке
 * вытеснят всё остальное, а вопрос оператора здесь другой — «видел ли бот
 * нужный кусок прайса вообще».
 */
export interface TariffContextTrace {
  sections: string[];
  rows: number;
}

export interface AnswerReasons {
  /** Контроли, сработавшие на этом ответе. Пусто — ни один не сработал. */
  humanReview: ReasonDetail[];
  tariffContext: TariffContextTrace;
  /** Числа, которых нет в источниках. Заполняется независимо от контура. */
  ungroundedValues: string[];
  /** Суммы, разошедшиеся с прайсом. */
  stalePrices: string[];
  /** Цены, приписанные не той услуге заверения. */
  priceContradictions: string[];
}
