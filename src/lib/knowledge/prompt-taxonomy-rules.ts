/**
 * Полный блок правил классификации, общий для всех трёх промптов
 * извлечения. Порядок фиксирован, чтобы диффы промптов оставались
 * читаемыми, а fingerprint — воспроизводимым.
 */
export const SHARED_TAXONOMY_RULES: readonly string[] = Object.freeze([
  ADJACENCY_IS_NOT_DEPENDENCY_RULE,
  UNCONDITIONAL_PROHIBITION_RULE,
  CONFIRMATORY_CLAUSE_RULE,
]);

/** Рендер общих правил таксономии одним блоком с заданным отступом. */
export function sharedTaxonomyRulesText(indent = ''): string {
  return SHARED_TAXONOMY_RULES.map((rule) => `${indent}${rule}`).join('\n');
}
