/**
 * Цены на заверение как таблица, а не как текст.
 *
 * Источник — клиентский «Прайс на перевод и заверение», действует с 01.01.2026,
 * таблица «Наименование услуги → Стоимость» (23 строки, разбор:
 * docs/bot-audit/02-price-documents.md §1). Взята именно она: таблица плоская и
 * однозначная. Тарифы на сам перевод (язык × срок × направление × категория,
 * ~1500 значений) сюда НЕ входят намеренно — там не разрешена граница 2 и 3
 * категории сложности, и цену перевода нельзя назвать автономно в принципе.
 *
 * Зачем. Бот сказал клиенту: «нотариальное заверение перевода — 260 рублей за
 * страницу». По прайсу это 1100 ₽ за документ, а 260 ₽/стр — заверение КОПИИ.
 * Ни один из существующих контролей этого не видит: судья не знал цен,
 * а заземление чисел (claim-grounding.ts) проверяет ПРОИСХОЖДЕНИЕ числа — 260 в
 * источниках есть, оно просто приписано не той услуге. Пока обе цены для системы
 * просто текст, такая ошибка неотличима от верного ответа.
 *
 * Что этот модуль делает и чего НЕ делает. Он не отвечает на вопросы о ценах:
 * замер на проде показал, что синтез отвечает на прямые ценовые вопросы верно
 * (6 из 6), и подменять верные ответы детерминированными — риск без выигрыша.
 * Он проверяет УЖЕ синтезированный ответ на противоречие прайсу.
 *
 * Где хранится. В коде, а не в базе — как apostille-authority.ts. Цена, которую
 * можно поправить в админке без ревью, превращает опечатку в детерминированно
 * неверный ответ клиенту. Прайс меняется раз в год; коммит с тестами дешевле
 * инцидента. Оба независимых критика (Kimi, Codex) сошлись на этом.
 */

/** Единица, в которой назначена цена. Сравнивается наравне со значением. */
export type PriceUnit = 'doc' | 'page' | 'mark' | 'visa' | 'standard_page';

export interface CertificationService {
  key: string;
  /** Название строго как в прайсе — чтобы сверка с бумагой была глазами. */
  label: string;
  /**
   * Цена, пригодная для механической сверки. `null` — строка прайса, которую
   * сверять нельзя: процент от чего-то («70% от стоимости 1 у.с.»), нижняя
   * граница («от 60 руб.») или составная («1000 тариф + 260/стр»). Такие строки
   * остаются в таблице как справка, но не порождают вердикта: сверять «от 60»
   * с ответом «80 рублей» значит объявлять противоречием верный ответ.
   */
  price: { amount: number; unit: PriceUnit } | null;
  /** Как цена записана в прайсе. Для сообщения оператору. */
  priceText: string;
  /**
   * Срочный аналог этой же услуги.
   *
   * Срочность в живых ответах называется отдельной фразой, а не прилагательным
   * при услуге: «Если нужно срочно, нотариальное заверение перевода обойдётся в
   * 1250 рублей». Опознаватель видит здесь обычную услугу (1100 ₽) и объявлял бы
   * верный ответ противоречием. Поймано запросом к проду, не тестом. Поэтому при
   * слове «срочно» в предложении допустимы обе цены — обычная и срочная.
   */
  urgentVariantKey?: string;
  /**
   * Опознаватель услуги в тексте. Части названия обязаны идти ВПЛОТНУЮ, без
   * `.*` между ними: иначе «нотариальное заверение КОПИИ перевода» совпадёт с
   * опознавателем «нотариальное заверение перевода» — то самое смешение, ради
   * которого модуль и написан.
   */
  pattern: RegExp;
}

