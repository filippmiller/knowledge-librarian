interface ServiceMatch {
  service: CertificationService;
  start: number;
  end: number;
  text: string;
}

/**
 * Все услуги, названные в отрезке текста. При пересечении совпадений остаётся
 * самое длинное: «срочное нотариальное заверение» перекрывает «нотариальное
 * заверение», и цена обязана достаться срочной услуге.
 */
function matchServices(segment: string): ServiceMatch[] {
  const raw: ServiceMatch[] = [];
  for (const service of CERTIFICATION_SERVICES) {
    const re = new RegExp(service.pattern.source, 'giu');
    let m: RegExpExecArray | null;
    while ((m = re.exec(segment)) !== null) {
      raw.push({ service, start: m.index, end: m.index + m[0].length, text: m[0] });
      if (m.index === re.lastIndex) re.lastIndex++;
    }
  }
  // Отбор по УБЫВАНИЮ длины совпадения, а не по позиции. «Двуязычное
  // нотариальное заверение» и «нотариальное заверение перевода» пересекаются,
  // но ни одно не содержит другое: первое начинается раньше, второе кончается
  // позже. Отбор по позиции отдавал цену общей услуге — двуязычное заверение
  // за 1300 объявлялось противоречием прайсу. Длина разрешает это однозначно.
  raw.sort((a, b) => b.end - b.start - (a.end - a.start) || a.start - b.start);

  const kept: ServiceMatch[] = [];
  for (const candidate of raw) {
    const overlaps = kept.some((k) => candidate.start < k.end && k.start < candidate.end);
    if (!overlaps) kept.push(candidate);
  }
  return kept.sort((a, b) => a.start - b.start);
}

interface PriceMention {
  amount: number;
  /** `null` — единица не названа: «1100 рублей». Тогда сверяется только сумма. */
  unit: PriceUnit | null;
  start: number;
  end: number;
  text: string;
}

/**
 * Порядок ветвей значим: `рубл[а-яё]+` обязан стоять ПЕРЕД `руб\.?`. Иначе
 * «1100 рублей за страницу» совпадало по короткой ветке «руб», хвост начинался
 * с «лей», единица не распознавалась вовсе — и ответ «1100 рублей за страницу»
 * (сумма верна, единица чужая) проходил проверку.
 */
const MONEY = String.raw`(?:₽|рубл[а-яё]+|руб\.?|р\.(?![\s.]*д))`;

const UNIT_PATTERNS: Array<{ unit: PriceUnit; source: string }> = [
  { unit: 'doc', source: String.raw`(?:за\s+)?(?:один\s+|1\s+|каждый\s+)?докум[а-яё]*|\/\s*док\.?` },
  { unit: 'standard_page', source: String.raw`(?:за\s+)?(?:1\s+|одну\s+)?усл[а-яё]*\.?\s*страниц[а-яё]*|\/\s*1?\s*у\.?\s*с\.?` },
  { unit: 'page', source: String.raw`(?:за\s+)?(?:одну\s+|1\s+|каждую\s+)?страниц[а-яё]*|\/\s*стр\.?|за\s+лист` },
  { unit: 'mark', source: String.raw`(?:за\s+)?(?:одну\s+|каждую\s+)?отметк[а-яё]*|\/\s*отметк[а-яё]*` },
  { unit: 'visa', source: String.raw`(?:за\s+)?(?:одну\s+|каждую\s+)?виз[а-яё]*|\/\s*виз[а-яё]*` },
];

/**
 * Цены в отрезке. Денежный маркер обязателен: без него «заверение занимает 40
 * минут» читалось бы как цена 40, а «оформление 40 минут» — живая фраза из
 * ответов бота.
 */
function matchPrices(segment: string): PriceMention[] {
  const out: PriceMention[] = [];
  const re = new RegExp(String.raw`(\d[\d\s   ]*)\s*${MONEY}`, 'giu');
  let m: RegExpExecArray | null;
  while ((m = re.exec(segment)) !== null) {
    const amount = Number(m[1].replace(/[\s   ]/g, ''));
    if (!Number.isFinite(amount) || amount === 0) continue;
    const tail = segment.slice(m.index + m[0].length, m.index + m[0].length + 40);
    let unit: PriceUnit | null = null;
    for (const spec of UNIT_PATTERNS) {
      // Единица обязана примыкать: «1100 руб. за документ», «260 руб./стр».
      // Иначе «1100 рублей. Пришлите документ» дало бы единицу «документ».
      if (new RegExp(String.raw`^[\s./]*(?:${spec.source})`, 'iu').test(tail)) {
        unit = spec.unit;
        break;
      }
    }
    out.push({ amount, unit, start: m.index, end: m.index + m[0].length, text: m[0].trim() });
  }
  return out;
}

