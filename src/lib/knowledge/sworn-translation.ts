/**
 * Присяжного перевода в России не существует.
 *
 * Повод — живой ответ бота, забракованный владельцем бюро 31.07.2026. На вопрос
 * «какой пакет документов нужен для подачи перевода в суд» бот предложил
 * «перевод, заверенный нотариусом, ИЛИ присяжный перевод — в зависимости от
 * того, какой суд принимает». Ответ пришёл из общих знаний модели: правил про
 * присяжный перевод в базе НОЛЬ.
 *
 * Слова владельца дословно: «В России нет присяжного перевода вообще! Не
 * существует! В России нотариальный перевод или перевод штампами в зависимости
 * от требований в конкретной ситуации. Но лучше нотариальный. Если суд за
 * рубежом, тогда там могут быть присяжные переводчики, но цену такого перевода
 * бот рассчитать не сможет».
 *
 * То же самое было установлено слепым тестом 30.07.2026
 * (docs/bot-audit/blind-test-sworn-translation.md §66) — и не дошло до базы.
 * Здесь оно записано так, чтобы дойти обязательно.
 *
 * Почему это не просто правило в базе. Ошибка родилась там, где базы нет вовсе:
 * на ветке общих знаний. Правило её не закроет — поиск по смыслу не находит
 * того, чего в базе нет. Нужна проверка САМОГО ОТВЕТА, независимая от того,
 * откуда он пришёл.
 */

import { splitSentences } from '@/lib/knowledge/sentences';

/** Упоминание присяжного перевода в любой форме. */
const SWORN = /присяжн/iu;

/**
 * Присяжный перевод назван как иностранная реальность — это верно и допустимо.
 * За рубежом институт существует, и клиенту про него сказать можно.
 */
const LOCATED_ABROAD =
  /за\s+рубеж|за\s+границ|иностранн|друг[а-яё]*\s+стран|в\s+европ|консульств|посольств|зарубежн|той\s+стран|принимающ[а-яё]*\s+стран/iu;

/**
 * Отрицание существования — это и есть верный ответ, глушить его нельзя.
 * «В России института присяжного перевода нет» обязано проходить.
 */
const DENIES_EXISTENCE =
  /не\s+существует|не\s+бывает|отсутству|не\s+предусмотрен|не\s+применяется|нет\s+инстит|инстит[а-яё]*\s+[^.]{0,40}нет|нет\s+присяжн|присяжн[а-яё]*\s+[^.]{0,30}\s+нет|не\s+делаем|не\s+оказываем|не\s+можем\s+(?:сделать|выполнить)/iu;

export interface SwornClaimViolation {
  sentence: string;
}

export interface SwornVerdict {
  /** Ответ не выдаёт присяжный перевод за доступный в России вариант. */
  safe: boolean;
  violations: SwornClaimViolation[];
}

/**
 * Не предлагает ли ответ присяжный перевод как услугу, доступную здесь.
 *
 * Правило намеренно грубое: любое упоминание присяжного перевода, не отнесённое
 * к загранице и не отрицающее его существование, считается нарушением. Цена
 * ошибки несимметрична — назвать клиенту несуществующую в стране услугу значит
 * пообещать то, чего не бывает, а лишний уход к человеку стоит одного
 * сообщения.
 */
export function checkSwornTranslationClaim(answer: string): SwornVerdict {
  const violations: SwornClaimViolation[] = [];
  for (const sentence of splitSentences(answer)) {
    if (!SWORN.test(sentence)) continue;
    if (LOCATED_ABROAD.test(sentence)) continue;
    if (DENIES_EXISTENCE.test(sentence)) continue;
    violations.push({ sentence: sentence.trim() });
  }
  return { safe: violations.length === 0, violations };
}

