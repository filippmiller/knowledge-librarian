const ABOUT_COURT = /(?:^|[^а-яё])суд[уаеы]?(?![а-яё])|для\s+суда|в\s+суд(?![а-яё])|судебн/iu;
const ABOUT_TRANSLATION = /перевод|заверени|нотариус|документ/iu;

/** Суд за границей — там присяжный переводчик возможен, но цену мы не считаем. */
const FOREIGN_COURT =
  /за\s+рубеж|за\s+границ|иностранн[а-яё]*\s+суд|суд[а-яё]*\s+(?:в|во)\s+(?:герман|итал|испан|франц|польш|чехи|греци|турци|израил|сша|канад|англи|британ|нидерланд|финлянд|австри|швейцар|болгар|сербии|кипр)/iu;

export type CourtTranslationVerdict =
  | { kind: 'russian_court' }
  | { kind: 'foreign_court' }
  | { kind: 'unknown' };

export function resolveCourtTranslation(question: string): CourtTranslationVerdict {
  if (!ABOUT_COURT.test(question)) return { kind: 'unknown' };
  if (!ABOUT_TRANSLATION.test(question)) return { kind: 'unknown' };
  return FOREIGN_COURT.test(question) ? { kind: 'foreign_court' } : { kind: 'russian_court' };
}
