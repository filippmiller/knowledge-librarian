/**
 * Кто ставит апостиль и действует ли территориальный признак.
 *
 * Источник — «Рабочая тетрадь стажёра» компании, страница 10 (разбор:
 * docs/bot-audit/04-trainee-notebook.md §1). Это внутренний обучающий материал,
 * по которому работают люди: таблица согласована, снабжена исключениями и
 * сносками. Она первична по отношению к 1723 правилам, извлечённым из
 * инструкций поштучно.
 *
 * Зачем отдельный модуль, а не правило в базе. Территориальность — это НЕ факт
 * о мире, который можно процитировать, а РЕШЕНИЕ: «можем ли мы взять этот
 * документ». Пока оно принимается поиском по смыслу, ответ зависит от того,
 * какой абзац окажется ближе к вопросу. Правило R-963 про Саратов в базе есть,
 * и бот всё равно отвечал неверно — маршрут до него не доходил.
 *
 * Главное, ради чего это написано: у образовательного комитета территориального
 * признака НЕТ. Формулировка «апостиль ставится только в регионе выдачи,
 * исключений нет», записанная в раннем диагнозе, неверна и стоила бы заказов:
 * диплом, выданный в Саратове, мы апостилируем в Петербурге законно.
 */

export type ApostilleAuthorityKey = 'min_justice' | 'zags' | 'mvd' | 'education';

export interface ApostilleAuthority {
  key: ApostilleAuthorityKey;
  label: string;
  /**
   * Действует ли территориальный признак: апостилируются только документы,
   * выданные в регионе обращения.
   */
  territorial: boolean;
  /** Срок, как он назван в тетради. Не выдумывать и не пересчитывать. */
  deadline: string;
  /** Нужна ли доверенность. */
  powerOfAttorney: string;
  /** Сноска тетради — то, что предлагать, когда прямой путь закрыт. */
  footnote?: string;
}

