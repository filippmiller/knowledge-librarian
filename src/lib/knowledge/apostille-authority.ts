/**
 * Типы документов по органам. Порядок проверки важен: справка о несудимости
 * упоминает слово «справка», которое встречается и у ВУЗов, поэтому МВД
 * проверяется раньше.
 *
 * Границы слов заданы через отрицательный просмотр назад по буквам: `\b` в JS
 * опирается на латиницу и перед кириллицей не срабатывает.
 */
const NOT_LETTER_BEFORE = '(?<![А-Яа-яЁёA-Za-z])';
const NOT_LETTER_AFTER = '(?![А-Яа-яЁёA-Za-z])';

const DOCUMENT_MATCHERS: Array<{ authority: ApostilleAuthorityKey; pattern: RegExp }> = [
  {
    authority: 'mvd',
    // «СОН» — внутреннее сокращение справки об отсутствии судимости. Границы
    // с обеих сторон обязательны и РАЗНЫЕ: слева просмотр назад, справа вперёд.
    // Один и тот же просмотр назад с обеих сторон проверял бы букву «н» самого
    // сокращения и никогда не срабатывал.
    pattern: new RegExp(
      `(?:несудим|о\\s+судимост|${NOT_LETTER_BEFORE}сон${NOT_LETTER_AFTER})`,
      'iu'
    ),
  },
  {
    authority: 'education',
    // Диплом и аттестат идут в комитет только С ПРИЛОЖЕНИЕМ; справки и
    // сертификаты из ВУЗов — наоборот, в Минюст. Это разные ветки, поэтому
    // «справка из вуза» ниже перехватывается отдельно.
    pattern:
      /(?:диплом|аттестат|удостоверени[а-яё]*\s+о\s+переквалиф|(?:^|[^а-яё])дпо(?:[^а-яё]|$)|образовательн[а-яё]*\s+документ)/iu,
  },
  {
    authority: 'zags',
    pattern:
      /(?:загс|свидетельств[а-яё]*\s+о\s+(?:рожден|брак|растор|смерт|усыновл|перемен)|справк[а-яё]*\s+о\s+рожден)/iu,
  },
  {
    authority: 'min_justice',
    pattern:
      /(?:нотариальн[а-яё]*\s+(?:копи|перевод|документ|доверенност)|доверенност|мфц|судебн[а-яё]*\s+документ|налогов[а-яё]*|справк[а-яё]*\s+из\s+вуза|сертификат[а-яё]*\s+из\s+вуза)/iu,
  },
];

/** К какому органу относится документ из вопроса. `null` — не определили. */
export function classifyApostilleDocument(question: string): ApostilleAuthorityKey | null {
  for (const matcher of DOCUMENT_MATCHERS) {
    if (matcher.pattern.test(question)) return matcher.authority;
  }
  return null;
}

export type IssuingRegion = 'local' | 'other' | 'unknown';

const LOCAL_REGION =
  /(?:санкт\s*петербург|петербург|(?:^|[^а-яё])спб(?:[^а-яё]|$)|ленинградск|лен\.?\s*обл)/iu;

/**
 * Города и формулировки, означающие «выдан не у нас». Список закрытый
 * намеренно: угадывать регион по любому топониму опаснее, чем не угадать —
 * ошибка здесь становится детерминированным отказом.
 */
const OTHER_REGION =
  /(?:друг[а-яё]*\s+(?:регион|город|област)|москв|перм|нижн|новосиб|екатеринбург|казан|самар|ростов|краснодар|воронеж|челябинск|волгоград|саратов|тюмен|иркутск|омск|уф[аеы]|красноярск|барнаул|владивосток|хабаровск|мурманск|архангельск|калининград|сочи|ставропол|белгород|тул[аеы]|ярославл|владимир|иванов|вологд|псков|новгород)/iu;

export function detectIssuingRegion(question: string): IssuingRegion {
  const local = LOCAL_REGION.test(question);
  const other = OTHER_REGION.test(question);
  // Названы оба — по одному вопросу не понять, где выдан документ, а где его
  // хотят подать. Молчим: неверный детерминированный ответ хуже уточнения.
  if (local && other) return 'unknown';
  if (other) return 'other';
  if (local) return 'local';
  return 'unknown';
}

export type TerritorialVerdict =
  /** Берём: территориальный признак не мешает. */
  | { kind: 'accept'; authority: ApostilleAuthority }
  /** Оригинал апостилировать здесь нельзя — документ выдан в другом регионе. */
  | { kind: 'reject_original'; authority: ApostilleAuthority }
  /** Не хватает данных для решения. */
  | { kind: 'unknown' };

/**
 * Единственное решение, которое принимает этот модуль: можем ли мы взять
 * документ на апостиль здесь.
 *
 * Решение выдаётся ТОЛЬКО когда известны оба слота. Kimi справедливо указал
 * главный риск такой таблицы: ошибка извлечения слота превращается из случайной
 * в детерминированную. Поэтому при любой неоднозначности — `unknown`, и вопрос
 * идёт обычным путём.
 */
export function resolveApostilleTerritoriality(
  question: string
): TerritorialVerdict {
  const key = classifyApostilleDocument(question);
  if (!key) return { kind: 'unknown' };
  const authority = APOSTILLE_AUTHORITIES[key];

  // У образовательного комитета признака нет — регион вообще не спрашиваем.
  if (!authority.territorial) return { kind: 'accept', authority };

  const region = detectIssuingRegion(question);
  if (region === 'unknown') return { kind: 'unknown' };
  return region === 'other'
    ? { kind: 'reject_original', authority }
    : { kind: 'accept', authority };
}
