/**
 * Деление ответа на предложения — общее для всех, кто судит о цене.
 *
 * Ценовые сторожа смотрят предложение целиком: сумма относится к услуге,
 * названной РЯДОМ с ней, а не где-то в ответе. Пока правило деления жило двумя
 * копиями в `certification-price` и `stale-price-check`, любая правка одной из
 * них тихо разводила сторожей по разным границам предложений — и один начинал
 * считать областью то, что другой уже не считал.
 */
export function splitSentences(text: string): string[] {
  return text.split(/(?<=[.!?])\s+|\n+/u);
}
