import { z } from 'zod';

/**
 * Непустая ОСМЫСЛЕННАЯ строка — одна реализация правила на весь контракт.
 *
 * `z.string().min(1)` пропускает `"   "`, `"\t"`, `"\n"`. Строка из одних
 * пробелов несёт ровно столько же смысла, сколько пустая, но при этом проходит
 * проверку «поле заполнено» — и дальше по коду считается заполненным. В этом
 * контракте цена такой строки высока: `reviewedBy` из пробелов означает
 * «подтверждено кем-то безымянным» и открывает `GLOBAL`, а `quote` из пробелов
 * означает «источник есть» там, где источника нет.
 *
 * Правило: непустая строка — это `trim().length > 0`, что `/\S/` и проверяет.
 */
export function nonBlankString(message: string) {
  return z.string().regex(/\S/, message);
}
