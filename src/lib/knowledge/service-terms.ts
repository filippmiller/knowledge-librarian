/**
 * Слова, которыми услуга прайса опознаётся в тексте. ОДНА реализация на всех.
 *
 * Раньше их было две: опознание услуги по вопросу резало окончания и знало
 * отраслевые сокращения, а сторож устаревших цен брал слова целиком и не знал
 * ни сокращений, ни служебных слов. Два модуля по-разному понимали одну и ту же
 * строку прайса — значит, вопрос и ответ про одну услугу могли разъехаться, и
 * разъезд был бы молчаливым. Найдено независимо аудитом Codex и CodeRabbit.
 *
 * Правила отбора здесь — политика, а не техника, и потому живут в одном месте.
 */

/** Служебные слова названия: в вопросе клиента их обычно нет. */
const STOPWORDS = /^(?:перед|через|после|включая|вместе|около|более|менее|также)$/iu;

/**
 * Предлоги и союзы. В вырожденном случае короткие слова становятся
 * ОБЯЗАТЕЛЬНЫМИ, и предлог в этой роли только вредит: «ТПП СПб (от 2-х дней)»
 * требовал бы от клиента слова «от».
 */
const FUNCTION_WORD = /^(?:на|по|до|из|за|без|от|для|при|над|под|про|как|или|но|со|ко|во)$/iu;

/**
 * Сокращения отрасли короче пяти букв, но именно они и отличают услугу:
 * ТПП, МЮ, МИД, СОН, ЗАГС, СПб, МСК. Порог длины их отбрасывал, и «ТПП СПб» не
 * опознавалась вовсе.
 */
const SHORT_SIGNIFICANT = /^(?:тпп|мю|мид|сон|загс|спб|мск|мо|ло|нзко|нз|егрюл|егрип|дпо)$/iu;

/**
 * Значимые слова названия услуги.
 *
 * Окончания срезаются грубо — этого хватает, чтобы «заверение» нашлось по
 * «заверения», но НЕ хватает, чтобы связать разные части речи: у
 * существительного и глагола разные корни, и для них есть поле синонимов.
 *
 * Название, от которого остался один общий корень, — это магнит на всю тему.
 * Измерено на корпусе из 180 реальных вопросов: «Перевод виз» теряла
 * различительное «виз» как слишком короткое, оставалось «перев», и в строку с
 * ценой 100 ₽ за визу проваливались ВСЕ шесть ценовых вопросов про перевод
 * (суммарная частота 31 из 443). Поэтому в вырожденном случае короткие слова
 * возвращаются в требуемые.
 *
 * Порог возврата — ДВЕ буквы: у «Апостиль МЮ МО (1 р.д.)» орган и регион
 * различают именно двухбуквенные «МЮ» и «МО». Цифры и обломки сокращений
 * («(10 р.д.)») не возвращаются — требовать от клиента написать «10 р д»
 * значит убить строку совсем.
 */
export function serviceTerms(text: string): string[] {
  // Скобки в названии — пояснение бухгалтера, а не признак услуги, и требовать
  // их слова от клиента нельзя. Измерено: строка «Нотариальное заверение
  // перевода (включая тех. работы)» не находилась самой частой формулировкой
  // клиента — «сколько стоит нотариальное заверение перевода», — потому что
  // слова «включая» и «работы» обязаны были присутствовать. То же у «(от 2-х
  // дней)» и «(10 р.д.)».
  //
  // Если после снятия скобок значимых слов не осталось вовсе, скобки
  // возвращаются: у «Стандартный срок (45 рабочих дней)» вне скобок нет ничего,
  // и без них строка перестала бы находиться совсем.
  const withoutParens = text.replace(/\([^)]*\)/gu, ' ');
  const source = /[а-яёa-z]{5}/iu.test(withoutParens) ? withoutParens : text;

  const words = source
    .toLowerCase()
    .split(/[^а-яёa-z0-9]+/u)
    .filter(Boolean)
    .filter((w) => !STOPWORDS.test(w));

  const stems = words
    .filter((w) => w.length >= 5 || SHORT_SIGNIFICANT.test(w))
    .map((w) => (w.length >= 5 ? w.slice(0, Math.max(5, w.length - 2)) : w));
  // Повторы раздували счёт совпадений и занижали требуемую долю.
  const unique = [...new Set(stems)];
  if (unique.length >= 2) return unique;

  const rescued = words.filter(
    (w) => w.length >= 2 && w.length < 5 && !/\d/u.test(w) && !FUNCTION_WORD.test(w)
  );
  return [...new Set([...unique, ...rescued])];
}
