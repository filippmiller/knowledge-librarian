/**
 * К чему подшивается нотариальный перевод: три маршрута исходника.
 *
 * Источник — прямые слова владельца (docs/bot-audit/03-price-rules-from-owner.md
 * §5): «Есть 3 варианта: ксерокопия, нотариальная копия, оригинал — всё зависит
 * от дальнейшего пути перевода».
 *
 * Зачем отдельный модуль. Замер на проде: шесть формулировок одного и того же
 * вопроса дали ЧЕТЫРЕ разных набора маршрутов, и в четырёх ответах из шести бот
 * утверждал «нужен именно оригинал». Это не неполнота, а противоречие фактам —
 * то есть ошибка по определению владельца. Причина в данных: правила R-417 и
 * R-333 называют два маршрута из трёх, правил про простую ксерокопию в базе нет
 * вовсе, а эталонные пары противоречат друг другу. Пока ответ собирает поиск по
 * смыслу, он будет зависеть от формулировки вопроса.
 *
 * Юридическое основание третьего маршрута. Нотариус, заверяя перевод,
 * свидетельствует подлинность подписи переводчика (ст. 80–81 Основ о нотариате)
 * и сам документ не удостоверяет — поэтому оригинал для этого действия не
 * требуется. Оригинал обязателен там, где нотариус свидетельствует ВЕРНОСТЬ
 * КОПИИ (ст. 77), то есть на маршруте нотариальной копии.
 *
 * Чего модуль не делает. Он не выбирает маршрут за клиента: выбор определяется
 * тем, куда документ подаётся, а этого из вопроса обычно не видно. Он называет
 * все три маршрута с условиями и спрашивает назначение — иначе ответ либо
 * неверен («нужен оригинал»), либо перекладывает решение на клиента («на ваш
 * выбор»), который путь документа знает не лучше нас.
 */

export interface SourceDocumentRoute {
  key: 'photocopy' | 'notarial_copy' | 'original';
  label: string;
  /** Нужен ли физический оригинал документа. */
  originalRequired: boolean;
  /** Когда этот маршрут выбирают. Формулировка владельца, не догадка. */
  chosenWhen: string;
}

export const SOURCE_DOCUMENT_ROUTES: SourceDocumentRoute[] = [
  {
    key: 'photocopy',
    label: 'простая ксерокопия или распечатка скана',
    originalRequired: false,
    chosenWhen: 'принимающая сторона не требует заверенного исходника',
  },
  {
    key: 'notarial_copy',
    label: 'нотариальная копия',
    originalRequired: true,
    chosenWhen: 'нужна легализация, апостиль или подача в строгую инстанцию',
  },
  {
    key: 'original',
    label: 'оригинал документа',
    originalRequired: true,
    chosenWhen: 'этого прямо требует принимающая сторона',
  },
];

const W = '[а-яё]*';

/** Вопрос вообще про нотариальный перевод или его заверение. */
const ABOUT_NOTARIAL_TRANSLATION = new RegExp(
  `нотариальн${W}\\s+перевод|нотариальн${W}\\s+заверени|` +
    `заверени${W}\\s+перевода|заверенн${W}\\s+перевод|перевод${W}\\s+у\\s+нотариус|` +
    `подшива|подошь|сшива`,
  'iu'
);

/**
 * Вопрос именно про ИСХОДНИК: нужен ли оригинал, к чему подшивается, можно ли
 * по скану. Без этого условия ветка перехватывала бы любой вопрос про
 * нотариальный перевод, включая цену и сроки.
 */
const ABOUT_SOURCE_DOCUMENT = new RegExp(
  `оригинал|исходник|к\\s+чему\\s+подшива|что\\s+подшива|` +
    `по\\s+скану|по\\s+фото|скан${W}\\s+достаточно|ксерокопи|` +
    `удал[её]нн|из\\s+друг${W}\\s+город|не\\s+могу\\s+привезти|не\\s+могу\\s+прислать`,
  'iu'
);

/**
 * Апостиль решает отдельная таблица (apostille-authority.ts), и вопрос про него
 * этой ветке не принадлежит вовсе.
 */
const APOSTILLE = /апостил/iu;

/**
 * Строгая инстанция, названная в вопросе.
 *
 * Замечание Kimi к первой версии замысла: исключён был только апостиль, а
 * «можно ли по скану для консульства», «перевод для суда» — те же строгие
 * инстанции, и ответ «достаточно скана» на них противоречил бы фактам. Список
 * закрытый: угадывать строгость по любому упоминанию организации опаснее, чем
 * не угадать.
 */
const STRICT_DESTINATION = new RegExp(
  // Нотариальной копии здесь намеренно НЕТ: это один из трёх маршрутов, а не
  // инстанция. Пока она стояла в списке, вопрос «к оригиналу, к копии или к
  // нотариальной копии?» — то есть просьба перечислить маршруты — попадал в
  // ветку строгой подачи и получал сужённый ответ.
  `легализац|консульств|консульск|посольств|` +
    `(?:^|[^а-яё])суд[уае]?(?![а-яё])|для\\s+суда|` +
    `гувм|фмс|мвд|миграцион|внж|рвп|гражданств|` +
    `вуз|университет|институт|министерств|госорган|росреестр|загс`,
  'iu'
);

export type SourceRouteVerdict =
  /** Назвать все три маршрута и спросить, куда подаётся документ. */
  | { kind: 'explain_routes' }
  /** Названа строгая инстанция: маршрут сужается до заверенного исходника. */
  | { kind: 'strict_destination' }
  | { kind: 'unknown' };

/**
 * Надо ли отвечать про маршруты исходника детерминированно.
 *
 * Молчим везде, где не уверены: неверный детерминированный ответ хуже, чем
 * обычный путь. Это же замечание Kimi к таблице территориальности — ошибка
 * извлечения слота из случайной становится постоянной.
 */
export function resolveSourceDocumentRoute(question: string): SourceRouteVerdict {
  if (APOSTILLE.test(question)) return { kind: 'unknown' };
  if (!ABOUT_NOTARIAL_TRANSLATION.test(question)) return { kind: 'unknown' };
  if (!ABOUT_SOURCE_DOCUMENT.test(question)) return { kind: 'unknown' };
  if (STRICT_DESTINATION.test(question)) return { kind: 'strict_destination' };
  return { kind: 'explain_routes' };
}
