let fp = 0;
let fn = 0;

console.log('=== ДОЛЖНЫ ПРОЙТИ (срабатывание = ложное, годный ответ уйдёт в эскалацию) ===\n');
for (const c of SHOULD_PASS) {
  const v = checkClientSafety(c.text);
  if (!v.safe) {
    fp++;
    console.log(`[ЛОЖНОЕ СРАБАТЫВАНИЕ] ${c.name}`);
    console.log(`   признаки: ${v.violations.join(', ')}`);
    console.log(`   текст: ${c.text}\n`);
  } else {
    console.log(`[ok] ${c.name}`);
  }
}

console.log('\n=== ДОЛЖНЫ ЛОВИТЬСЯ (пропуск = утечка клиенту) ===\n');
for (const c of SHOULD_CATCH) {
  const v = checkClientSafety(c.text);
  if (v.safe) {
    fn++;
    console.log(`[ПРОПУСК] ${c.name}`);
    console.log(`   текст: ${c.text}\n`);
  } else {
    console.log(`[ok] ${c.name} → ${v.violations.join(', ')}`);
  }
}

console.log(`\n=== ИТОГ ===`);
