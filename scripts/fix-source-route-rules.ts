function flat(s: string): string {
  return s.replace(/\s+/g, ' ').trim();
}

function banner(title: string): void {
  console.log(`\n${'='.repeat(72)}\n${title}\n${'='.repeat(72)}`);
}

/** Клиентский текст обязан проходить сигнализацию утечки — иначе ответ уйдёт в
 *  эскалацию и до клиента не дойдёт. Проверяем ДО записи, а не после. */
function assertClientSafe(label: string, text: string): void {
  const verdict = checkClientSafety(text);
  console.log(`  сигнализация утечки: ${verdict.safe ? 'ok' : 'СРАБОТАЛА — ' + verdict.violations.join(', ')}`);
  if (!verdict.safe) {
    throw new Error(`Клиентский текст «${label}» не проходит checkClientSafety — запись отменена`);
  }
}

async function updateRule(
  id: string,
  expectCode: string,
  title: string,
  body: string
): Promise<'changed' | 'noop'> {
  const rows = await prisma.rule.findMany({ where: { ruleCode: expectCode } });
  console.log(`\n[${expectCode}] записей с этим кодом в базе: ${rows.length}`);
  if (rows.length !== 1) {
    throw new Error(`Ожидалась ровно одна запись с кодом ${expectCode}, найдено ${rows.length} — правка отменена`);
  }
  const current = rows[0];
  if (current.id !== id) {
    throw new Error(`Код ${expectCode} указывает на id=${current.id}, а скрипт нацелен на ${id} — правка отменена`);
  }

  console.log(`  id=${current.id} status=${current.status} audience=${current.audience} confidence=${current.confidence} scenario=${current.scenarioKey ?? '-'}`);
  console.log(`  ДО  title: ${flat(current.title)}`);
  console.log(`  ДО  body : ${flat(current.body)}`);
  console.log(`  ПОСЛЕ title: ${flat(title)}`);
  console.log(`  ПОСЛЕ body : ${flat(body)}`);

  if (current.audience === 'CLIENT_SAFE') assertClientSafe(expectCode, body);

  if (current.title === title && current.body === body) {
    console.log('  → уже применено, изменений нет');
    return 'noop';
  }
  if (!APPLY) {
    console.log('  → СУХОЙ ПРОГОН: запись не выполнена');
    return 'changed';
  }
  await prisma.rule.update({ where: { id }, data: { title, body } });
  console.log('  → записано');
  return 'changed';
}

async function ensurePhotocopyRule(): Promise<'created' | 'updated' | 'noop'> {
  const existing = await prisma.rule.findFirst({
    where: { title: NEW_RULE_TITLE },
  });

  if (existing) {
    console.log(`\n[новое правило] уже существует: ${existing.ruleCode} id=${existing.id} audience=${existing.audience}`);
    console.log(`  ДО  body : ${flat(existing.body)}`);
    console.log(`  ПОСЛЕ body: ${flat(NEW_RULE_BODY)}`);
    assertClientSafe(NEW_RULE_TITLE, NEW_RULE_BODY);
    if (existing.body === NEW_RULE_BODY && existing.audience === 'CLIENT_SAFE' && existing.status === 'ACTIVE') {
      console.log('  → уже применено, изменений нет');
      return 'noop';
    }
    if (!APPLY) {
      console.log('  → СУХОЙ ПРОГОН: запись не выполнена');
      return 'updated';
    }
    await prisma.rule.update({
      where: { id: existing.id },
      data: { body: NEW_RULE_BODY, audience: 'CLIENT_SAFE', status: 'ACTIVE' },
    });
    console.log('  → обновлено');
    return 'updated';
  }

  const allCodes = await prisma.rule.findMany({
    where: { ruleCode: { startsWith: 'R-' } },
    select: { ruleCode: true },
  });
  const maxNum = allCodes.reduce((max, r) => {
    const n = parseInt(r.ruleCode.replace(/^R-/i, ''), 10) || 0;
    return n > max ? n : max;
  }, 0);
  const newCode = `R-${maxNum + 1}`;

  console.log(`\n[новое правило] будет создано с кодом ${newCode} (максимум в базе: R-${maxNum})`);
  console.log(`  title: ${flat(NEW_RULE_TITLE)}`);
  console.log(`  body : ${flat(NEW_RULE_BODY)}`);
  console.log('  audience: CLIENT_SAFE, documentId: null, scenarioKey: null (маршрут общий, не сценарный)');
  assertClientSafe(NEW_RULE_TITLE, NEW_RULE_BODY);

  if (!APPLY) {
    console.log('  → СУХОЙ ПРОГОН: запись не выполнена');
    return 'created';
  }
  const created = await prisma.rule.create({
    data: {
      ruleCode: newCode,
      title: NEW_RULE_TITLE,
      body: NEW_RULE_BODY,
      // Ранжирование поднимает правила с confidence >= 1 (см. rankByQuestion в
      // enhanced-answering-engine). Маршрут исходника — прямые слова владельца,
      // а не извлечение модели, поэтому уверенность полная.
      confidence: 1.0,
      status: 'ACTIVE',
      audience: 'CLIENT_SAFE',
      sourceSpan: {
        quote: 'Есть 3 варианта: ксерокопия, нотариальная копия, оригинал — всё зависит от дальнейшего пути перевода',
        locationHint: 'Прямые слова владельца бюро, docs/bot-audit/03-price-rules-from-owner.md §5',
      },
    },
  });
  console.log(`  → создано: ${created.ruleCode} id=${created.id}`);
  return 'created';
}

async function fixQaPairs(): Promise<number> {
  let changed = 0;
  for (const fix of QA_FIXES) {
    const qa = await prisma.qAPair.findUnique({ where: { id: fix.id } });
    if (!qa) {
      console.log(`\n[QA ${fix.id}] НЕ НАЙДЕНА — пропуск`);
      continue;
    }
    console.log(`\n[QA ${fix.id}] audience=${qa.audience} status=${qa.status}`);
    console.log(`  причина: ${fix.why}`);
    console.log(`  вопрос : ${flat(qa.question)}`);
    console.log(`  ДО     : ${flat(qa.answer)}`);
    console.log(`  ПОСЛЕ  : ${flat(fix.answer)}`);
    if (qa.audience === 'CLIENT_SAFE') assertClientSafe(fix.id, fix.answer);
    if (qa.answer === fix.answer) {
      console.log('  → уже применено, изменений нет');
      continue;
    }
    changed += 1;
    if (!APPLY) {
      console.log('  → СУХОЙ ПРОГОН: запись не выполнена');
      continue;
    }
    await prisma.qAPair.update({ where: { id: fix.id }, data: { answer: fix.answer } });
    console.log('  → записано');
  }
  return changed;
}

async function main() {
  console.log(APPLY ? '### РЕЖИМ ЗАПИСИ (--apply)' : '### СУХОЙ ПРОГОН (без --apply ничего не пишется)');

  banner('1. R-417 — внутренний контур: область действия + три маршрута');
  await updateRule(R417_ID, 'R-417', R417_TITLE, R417_BODY);

  banner('2. R-333 — клиентский контур: область действия + три маршрута');
  await updateRule(R333_ID, 'R-333', R333_TITLE, R333_BODY);

  banner('3. Недостающее правило про маршрут простой ксерокопии');
  await ensurePhotocopyRule();

  banner('4. Эталонные пары, противоречащие словам владельца');
  const qaChanged = await fixQaPairs();
  console.log(`\nпар к правке: ${qaChanged}`);

  await prisma.$disconnect();
}

main().catch(async (e) => {
  console.error('\nОШИБКА:', e instanceof Error ? e.message : e);
  await prisma.$disconnect();
  process.exit(1);
});
