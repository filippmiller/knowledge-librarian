/**
 * Правка данных: три маршрута исходника нотариального перевода.
 *
 * Почему потребовалась. Владелец: «Есть 3 варианта: ксерокопия, нотариальная
 * копия, оригинал — всё зависит от дальнейшего пути перевода». В базе правила
 * называли два маршрута из трёх, а эталонная пара прямо утверждала «подшивается
 * именно к оригиналу». Детерминированная ветка (src/lib/knowledge/
 * source-document-route.ts) перехватывает только ПРЯМОЙ вопрос про исходник;
 * соседние формулировки («что вы прикладываете к переводу для посольства»,
 * «чем отличается перевод с ксерокопии») по-прежнему собираются поиском по
 * смыслу и вытаскивают неполные правила.
 *
 * Что важно про R-417 и R-333. Оба лежат в сценарии apostille.min_justice и
 * происходят из инструкций по апостилю. В СВОЁМ контексте ограничение двумя
 * маршрутами верно: перевод, подшитый к простой ксерокопии, на апостиль не
 * принимают. Дефект не в самом ограничении, а в том, что оно записано БЕЗ
 * ОБЛАСТИ ДЕЙСТВИЯ и читается как общее правило нотариального перевода. Поэтому
 * правка не «дописывает третий маршрут» механически, а возвращает область
 * действия и рядом называет полную картину из трёх маршрутов с условием выбора.
 *
 * Юридическое основание третьего маршрута: нотариус, заверяя перевод,
 * свидетельствует подлинность подписи переводчика (ст. 80–81 Основ о нотариате)
 * и сам документ не удостоверяет — оригинал для этого действия не нужен.
 * Оригинал обязателен там, где свидетельствуется верность копии (ст. 77).
 *
 * Запуск:
 *   railway run npx tsx scripts/fix-source-route-rules.ts            # сухой прогон
 *   railway run npx tsx scripts/fix-source-route-rules.ts --apply    # запись
 *
 * Скрипт идемпотентен: повторный запуск ничего не меняет и печатает «уже
 * применено».
 */
