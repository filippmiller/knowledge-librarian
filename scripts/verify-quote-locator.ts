function run(): number {
  let failed = 0;

  for (const c of CASES) {
    const match = locateQuote(c.text, c.quote);
    const problems: string[] = [];

    if (!c.expect) {
      if (match) {
        problems.push(
          `ожидали «не найдено», получили ${match.kind} → ${JSON.stringify(c.text.slice(match.start, match.end))}`
        );
      }
    } else if (!match) {
      problems.push(`ожидали ${c.expect.kind}, совпадение не найдено`);
    } else {
      const highlight = c.text.slice(match.start, match.end);
      if (match.kind !== c.expect.kind) {
        problems.push(`степень совпадения: ожидали ${c.expect.kind}, получили ${match.kind}`);
      }
      if (highlight !== c.expect.highlight) {
        problems.push(
          `подсвечено ${JSON.stringify(highlight)}, ожидали ${JSON.stringify(c.expect.highlight)}`
        );
      }
      if (c.expect.ambiguous !== undefined && match.ambiguous !== c.expect.ambiguous) {
        problems.push(`пометка «догадка»: ожидали ${c.expect.ambiguous}, получили ${match.ambiguous}`);
      }
      if (c.expect.minCoverage !== undefined && match.coverage < c.expect.minCoverage) {
        problems.push(`доля совпадения ${match.coverage.toFixed(2)} ниже ожидаемой ${c.expect.minCoverage}`);
      }
    }

    if (problems.length) {
      failed++;
      console.log(`FAIL  ${c.name}`);
      for (const p of problems) console.log(`        ${p}`);
    } else {
      console.log(`ok    ${c.name}`);
    }
  }

  console.log(`\n${CASES.length - failed}/${CASES.length} кейсов прошло`);
  return failed;
}

process.exit(run() > 0 ? 1 : 0);
