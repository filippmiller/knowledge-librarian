let failed = 0;
let checks = 0;

for (const c of CASES) {
  const verdict = checkCertificationPriceAttribution(c.answer);
  const found = !verdict.consistent;

  checks += 1;
  let ok = found === c.expectContradiction;

  if (ok && c.expectService) {
    checks += 1;
    const hit = verdict.contradictions.some((x) => x.serviceKey === c.expectService);
    if (!hit) ok = false;
  }

  if (!ok) failed++;
  console.log(`[${ok ? 'ok  ' : 'FAIL'}] ${c.name}`);
  if (verdict.contradictions.length) {
    for (const x of verdict.contradictions) {
      console.log(`        нашли: ${x.serviceLabel} → назвал «${x.claimed}», прайс «${x.expected}»`);
    }
  }
  if (!ok) {
    console.log(`        ОЖИДАЛОСЬ противоречие=${c.expectContradiction}, получено ${found}`);
    console.log(`        ответ: ${c.answer}`);
  }
}

// Полнота таблицы: 23 строки прайса, из них сверяемых — те, у которых точная
// пара «сумма + единица». Проверяется здесь, чтобы потеря строки при правке
// прайса не прошла молча.
checks += 1;
const total = CERTIFICATION_SERVICES.length;
const checkable = CERTIFICATION_SERVICES.filter((s) => s.price !== null).length;
const tableOk = total === 23 && checkable === 16;
if (!tableOk) failed++;
console.log(
  `[${tableOk ? 'ok  ' : 'FAIL'}] таблица прайса: строк ${total} (ожидалось 23), сверяемых ${checkable} (ожидалось 16)`
);

console.log(`\nкейсов: ${CASES.length}, проверок: ${checks}, провалено: ${failed}`);
process.exit(failed > 0 ? 1 : 0);
