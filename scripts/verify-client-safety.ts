for (const c of cases) {
  const verdict = checkClientSafety(c.answer);
  const ok = verdict.safe === c.expectSafe;
  if (!ok) failed++;
  console.log(
    `${ok ? 'PASS' : 'FAIL'}  ${c.name}\n      ожидали safe=${c.expectSafe} получили safe=${verdict.safe}` +
      (verdict.violations.length ? ` [${verdict.violations.join(', ')}]` : '')
  );
}

console.log(`\n${cases.length - failed}/${cases.length} прошло`);
if (failed > 0) process.exit(1);
