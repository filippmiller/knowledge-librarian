/** Все синонимы одним списком — нужен проверке и отчёту. */
export function allProposedSynonyms(): Array<{ serviceName: string; synonym: string }> {
  return TARIFF_SYNONYMS.flatMap((p) =>
    p.synonyms.map((synonym) => ({ serviceName: p.serviceName, synonym }))
  );
}

/**
 * Объединение старого и нового списка.
 *
 * Именно объединение, а не замена: поле редактируется владельцем через админку,
 * и повторный запуск сева не должен стирать то, что человек добавил руками.
 * Сравнение регистронезависимое — иначе «Нотариальная копия» и «нотариальная
 * копия» жили бы в поле как два разных синонима.
 */
export function mergeSynonyms(existing: string[], proposed: string[]): string[] {
  const seen = new Map<string, string>();
  for (const s of [...existing, ...proposed]) {
    const key = s.trim().toLowerCase();
    if (key && !seen.has(key)) seen.set(key, s.trim());
  }
  return [...seen.values()];
}

const APPLY = process.argv.includes('--apply');

async function main() {
  console.log(`\n=== СЕВ СИНОНИМОВ ТАРИФНОЙ СЕТКИ ${APPLY ? '(ЗАПИСЬ)' : '(СУХОЙ ПРОГОН)'} ===\n`);

  let planned = 0;
  let unchanged = 0;
  let missing = 0;
  let ambiguous = 0;

  for (const proposal of TARIFF_SYNONYMS) {
    const rows = await prisma.tariff.findMany({
      where: { serviceName: proposal.serviceName, isActive: true },
      select: { naturalKey: true, serviceName: true, synonyms: true },
    });

    if (rows.length === 0) {
      // Синоним, привязанный к несуществующей строке, молча ничего не делает —
      // поэтому он не пропускается, а объявляется ошибкой.
      console.log(`[НЕТ СТРОКИ] «${proposal.serviceName}»`);
      missing += 1;
      continue;
    }
    if (rows.length > 1) {
      // Одно название на несколько строк — это варианты по сроку. Синонимы
      // легли бы на все сразу, и опознание вернуло бы перечень вариантов,
      // а не цену. Такие случаи разбираются руками, а не севом.
      console.log(`[НЕОДНОЗНАЧНО] «${proposal.serviceName}» — строк: ${rows.length}`);
      ambiguous += 1;
      continue;
    }

    const row = rows[0];
    const merged = mergeSynonyms(row.synonyms ?? [], proposal.synonyms);
    const changed =
      merged.length !== (row.synonyms ?? []).length ||
      merged.some((s, i) => s !== (row.synonyms ?? [])[i]);

    if (!changed) {
      unchanged += 1;
      console.log(`[уже есть]  «${proposal.serviceName}» — ${merged.length} синонимов`);
      continue;
    }

    planned += 1;
    console.log(`[${APPLY ? 'записано ' : 'запланир.'}] «${proposal.serviceName}»`);
    for (const s of proposal.synonyms) console.log(`              · ${s}`);
    console.log(`              источник: ${proposal.source}`);

    if (APPLY) {
      await prisma.tariff.update({
        where: { naturalKey: row.naturalKey },
        data: { synonyms: merged },
      });
    }
  }

  console.log('\n=== ИТОГ ===');
  console.log(`  услуг в предложении:     ${TARIFF_SYNONYMS.length}`);
  console.log(`  синонимов всего:         ${allProposedSynonyms().length}`);
  console.log(`  ${APPLY ? 'записано' : 'к записи'}:                ${planned}`);
  console.log(`  уже совпадает:           ${unchanged}`);
  console.log(`  строк не найдено:        ${missing}`);
  console.log(`  название неоднозначно:   ${ambiguous}`);
  if (!APPLY) console.log('\nЭто сухой прогон. Для записи: --apply');
  if (missing > 0 || ambiguous > 0) {
    console.log('\nЕсть непривязанные предложения — сев неполон, разберись до записи.');
  }

  await prisma.$disconnect();
  process.exit(missing > 0 || ambiguous > 0 ? 1 : 0);
}

