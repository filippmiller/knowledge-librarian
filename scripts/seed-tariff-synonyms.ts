/**
 * Заполнение поля `Tariff.synonyms` — слов, которыми услугу называет КЛИЕНТ.
 *
 * Запуск (сухой прогон, по умолчанию):
 *   railway run npx tsx scripts/seed-tariff-synonyms.ts
 * Запись:
 *   railway run npx tsx scripts/seed-tariff-synonyms.ts --apply
 *
 * ЗАЧЕМ. Опознание услуги идёт по словам САМОЙ сетки (`tariff-lookup.ts`), и
 * пока поле пустое, прайс находится только собственными словами прайса. Хуже
 * того, у половины строк официальное название содержит служебный хвост —
 * «(включая тех. работы)», «(пошлина включена в стоимость)», «(2-я и 3-я
 * категории)». Опознание требует ВСЕ значимые слова названия, поэтому самый
 * частый вопрос отрасли — «сколько стоит нотариальное заверение перевода» —
 * не находил строку 1100 ₽ из-за слова «работы», которого клиент не пишет
 * никогда. Синонимы здесь в первую очередь снимают этот хвост, и лишь во
 * вторую — добавляют клиентскую лексику.
 *
 * ГЛАВНОЕ ПРАВИЛО ОТБОРА: синоним обязан подходить РОВНО ОДНОЙ услуге.
 * Общее слово («апостиль», «перевод», «заверение») в синоним не выносится:
 * теневой прогон уже показал, во что обходится магнит — строка «Перевод виз»
 * с ценой 100 ₽ притянула все шесть ценовых вопросов про перевод
 * (docs/bot-audit/15-tariff-shadow-run.md §4.1). Услуга, для которой
 * специфичного синонима не существует, остаётся с пустым полем: молчание
 * дешевле неверной цены.
 *
 * ПОЧЕМУ СИНОНИМЫ ЗАПИСАНЫ ИМЕННО В ТАКОЙ ФОРМЕ. `serviceTerms` режет слово до
 * `length - 2` букв, но только если в нём не меньше пяти букв; пятибуквенные
 * слова не режутся вовсе. Поэтому «копия», «копии» и «копию» — три разные
 * основы, и каждая падежная форма, которую реально пишет клиент, вынесена
 * отдельным синонимом. По той же причине берутся короткие формы («штамп», а не
 * «штампами»): основа «штамп» найдётся в любом падеже, основа «штампа» — нет.
 *
 * ИСТОЧНИКИ (каждый синоним взят из данных, а не придуман):
 *   К  — корпус 180 реальных вопросов клиентов с ответами операторов,
 *        docs/email-bot/may2026-knowledge-base-final.json (номер вопроса).
 *   Б  — каталог услуг Битрикса, docs/email-bot/price-catalog.json: это те
 *        названия, которыми компания сама печатает услугу в бланке заказа.
 *   Т  — тетрадь стажёра, docs/bot-audit/04-trainee-notebook.md.
 *   В  — правила владельца, docs/bot-audit/03-price-rules-from-owner.md.
 *   П  — само название строки прайса, освобождённое от служебного хвоста.
 *
 * Разбор, почему каждый синоним специфичен, и список услуг, оставленных БЕЗ
 * синонимов, — в docs/bot-audit/16-tariff-synonyms.md.
 */
